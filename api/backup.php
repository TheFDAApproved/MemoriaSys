<?php

declare(strict_types=1);

/**
 * Database Backup Endpoint
 *
 * GET    /backup               -> List all available backup files
 * GET    /backup/{filename}    -> Download a specific backup file
 * POST   /backup               -> Create a new data-only backup (5-file retention)
 * PUT    /backup/{filename}    -> Restore the database from a backup file
 *
 * -----------------------------------------------------------------------------
 * Timezone policy
 * -----------------------------------------------------------------------------
 * Filenames and the GET listing MUST agree on a single wall clock. The filename
 * is stamped by MySQL via DATE_FORMAT(NOW(), …) in the session timezone, so the
 * listing must be formatted the same way — not via PHP's date(), which reads an
 * entirely independent php.ini timezone.
 *
 * Previously the listing used date('Y-m-d H:i:s', filemtime($file)). When
 * php.ini was on UTC and MySQL was on Asia/Manila, that produced an 8-hour skew
 * against the filename. The rules now are:
 *
 *   1. MySQL is the source of truth for "now" — see dbTimezone().
 *   2. The listing prefers the timestamp baked into the filename (it was
 *      generated by NOW(), so it *is* the DB clock).
 *   3. Any fallback path formats filemtime() explicitly in the DB timezone.
 *
 * Nothing here relies on PHP's global date.timezone matching MySQL's.
 *
 * -----------------------------------------------------------------------------
 * Concurrency policy
 * -----------------------------------------------------------------------------
 * Backup creation and database restore are destructive, non-atomic operations.
 * A single exclusive lock (`.operation.lock`) serializes them: at most one
 * POST/PUT runs at a time. A second request gets an immediate 409 instead of
 * corrupting an in-flight dump or fighting over TRUNCATE statements.
 *
 * The lock is best-effort within one server. If this app is ever deployed
 * behind multiple PHP workers on different machines, replace flock() with
 * MySQL GET_LOCK() or a row lock in a `locks` table.
 *
 * -----------------------------------------------------------------------------
 * Consistency policy
 * -----------------------------------------------------------------------------
 * createBackup() reads every table inside one REPEATABLE READ transaction that
 * was opened with WITH CONSISTENT SNAPSHOT. This means every SELECT sees the
 * same MVCC view of the database — the dump reflects one instant, not a
 * sequence of instants as the live app writes between tables. Writes from the
 * live app are NOT blocked; they simply aren't visible to the backup.
 *
 * restoreBackup() is still not atomic. TRUNCATE is DDL and forces an implicit
 * commit, so the restore cannot be wrapped in a transaction. Instead, the PUT
 * handler takes a safety backup immediately before running the restore; if the
 * restore fails midway, the admin has a known-good file to roll back to.
 *
 * -----------------------------------------------------------------------------
 * Security note
 * -----------------------------------------------------------------------------
 * The backups/ directory MUST NOT be reachable as a static directory through
 * the web server. If Apache/nginx serves files from here directly, anyone can
 * download a full dump without hitting this endpoint or authenticating.
 * Add a deny-all rule for /backups/ in the vhost config.
 */

define('ITS_ME_JUSTTOVERIFY', true);

require_once 'checkuser.php';
require_once 'logger.php';

const BACKUP_LIMIT       = 5;
const BACKUP_FILE_REGEX  = '/^[A-Za-z0-9._-]+\.sql$/';
const BACKUP_NAME_PREFIX = 'memoria_db_';

$userData = checkuser();

if (($userData['role'] ?? null) !== ROLE_ADMIN) {
    systemLog("{$userData['name']} ({$userData['username']}) attempted to backup or something here lol", $userData['user_id']);
    Response::error('Forbidden. Insufficient privileges.', 403);
}

// -----------------------------------------------------------------------------
// 0. Best-effort sync of PHP's clock with the DB session timezone
// -----------------------------------------------------------------------------
// Convenience only — a fallback for any stray date()/time() callers we don't
// control. It is NOT the source of truth: every timestamp produced below is
// formatted explicitly via dbTimezone().
//
// Quirks handled here:
//   * PHP's date_default_timezone_set() accepts only IANA names. It rejects
//     fixed offsets like '+08:00' even though DateTimeZone accepts them.
//     Offsets are therefore converted to a canonical IANA name first.
//   * 'SYSTEM' is a valid MySQL value but NOT a valid PHP timezone.
//   * If conversion fails, we silently skip — every code path here already
//     formats in the DB zone explicitly, so the global default is cosmetic.
if (defined('DB_TIMEZONE') && DB_TIMEZONE !== '' && strtoupper((string) DB_TIMEZONE) !== 'SYSTEM') {
    $tzValue = (string) DB_TIMEZONE;

    // Normalise a fixed offset ('+08:00', '-05:30') to a real IANA name.
    if (preg_match('/^([+-])(\d{2}):(\d{2})$/', $tzValue, $m)) {
        $offsetSeconds = ((int) $m[2] * 3600 + (int) $m[3] * 60) * ($m[1] === '-' ? -1 : 1);
        $name = timezone_name_from_abbr('', $offsetSeconds, 0);
        $tzValue = ($name !== false) ? $name : null;
    }

    if ($tzValue !== null && !@date_default_timezone_set($tzValue)) {
        error_log('backup.php: DB_TIMEZONE "' . DB_TIMEZONE . '" is not a valid PHP timezone.');
    }
}

@set_time_limit(0);

